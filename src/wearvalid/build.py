"""Load the data corpus, grade every device x claim cell, and emit outputs.

Outputs (written to ./build by default):
  - MATRIX.md     human-readable leaderboard with per-cell rationale
  - matrix.csv    machine-readable, one row per device x claim cell
  - heatmap.svg   color-coded grid for embedding in the README

Run:  python -m wearvalid build
"""
import csv
import json
import os
from collections import defaultdict

import yaml

from .grade import grade_cell
from .normalize import normalize
from .heatmap import GRADE_COLOR, render_svg

GRADE_ORDER = ["A", "B", "C", "D", "F", "N"]
GRADE_LABEL = {
    "A": "Established valid",
    "B": "Conditionally valid / good but limited",
    "C": "Contested / insufficient",
    "D": "Unvalidated but marketed",
    "F": "Refuted",
    "N": "Not validatable (composite)",
}


def _load_yaml(path):
    with open(path, "r") as fh:
        return yaml.safe_load(fh)


def load_corpus(data_dir):
    swc = _load_yaml(os.path.join(data_dir, "swc.yaml"))
    claims = {c["id"]: c for c in _load_yaml(os.path.join(data_dir, "claims.yaml"))}
    devices = {d["id"]: d for d in _load_yaml(os.path.join(data_dir, "devices.yaml"))}

    studies = []
    sdir = os.path.join(data_dir, "studies")
    for fn in sorted(os.listdir(sdir)):
        if fn.endswith((".yaml", ".yml")):
            studies.append(_load_yaml(os.path.join(sdir, fn)))
    return swc, claims, devices, studies


def collect_measurements(claims, studies):
    """Group normalized measurements by (device, claim)."""
    cells = defaultdict(list)
    for st in studies:
        is_review = st.get("tier") in ("systematic_review", "umbrella_review")
        for m in st.get("measurements", []):
            claim = claims[m["claim"]]
            canon = normalize(m["reported"])
            cells[(m["device"], m["claim"])].append({
                "canon": canon,
                "independent": st.get("independent", True),
                "criterion": m.get("criterion", "unspecified"),
                "is_gold": m.get("criterion") in claim.get("gold_criteria", []),
                "is_review": is_review,
                "label": "%s (%s)" % (st["id"], m.get("condition", "n/a")),
                "study": st["id"],
            })
    return cells


def grade_all(swc, claims, devices, studies):
    cells = collect_measurements(claims, studies)

    # Universe of cells = every measured cell + every marketed cell.
    universe = set(cells.keys())
    for d in devices.values():
        for claim_id in d.get("markets", []):
            universe.add((d["id"], claim_id))

    verdicts = []
    for (device_id, claim_id) in sorted(universe):
        claim = claims[claim_id]
        swc_val = (swc.get(claim_id) or {}).get("swc")
        marketed = claim_id in devices.get(device_id, {}).get("markets", [])
        v = grade_cell(device_id, claim, cells.get((device_id, claim_id), []),
                       swc_val, marketed=marketed)
        verdicts.append(v)
    return verdicts


def coverage_stats(verdicts):
    counts = {g: 0 for g in GRADE_ORDER}
    for v in verdicts:
        counts[v.grade] += 1
    return counts


